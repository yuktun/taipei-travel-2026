export function storiesFor(item) {
  if (item?.kind !== 'event') return [];
  const name = [item.title,item.place].filter(Boolean).join(' ');
  const note = String(item.note ?? '');
  const south = /故宮南|南部院區|Southern Branch/i.test(name);
  const eligible = stories.filter(s => !(south && s.title.startsWith('故宮')));
  const main = eligible.filter(s => s.match.test(name));
  // A card can group its destinations in the note rather than the title. Avoid
  // accidentally picking up a transfer stop from directions on a named card.
  const matches = main.length ? main : eligible.filter(s => s.match.test(note));
  return matches;
}
